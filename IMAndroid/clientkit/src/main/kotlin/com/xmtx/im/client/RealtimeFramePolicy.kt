package com.xmtx.im.client

import com.xmtx.imclientkit.generated.im.realtime.v2.Envelope
import com.xmtx.imclientkit.generated.im.realtime.v2.Envelope.BodyCase.*

/** Exhaustive V55 direction/lifecycle classification, matching Swift V2TCPFramePolicy. */
enum class RealtimeFramePolicy {
    Handshake, Control, Ephemeral, Read, Mutation, ServerOnly;
    val permitsAutomaticReplay:Boolean get()=false
    fun context(scoped:NetworkWorkContext?=null):NetworkWorkContext=when(this) {
        Handshake,ServerOnly->throw ClientFailure.Protocol()
        Control->NetworkWorkContext("realtime",NetworkWorkPriority.Critical,NetworkWorkKind.Authentication)
        Ephemeral->NetworkWorkContext("realtime",NetworkWorkPriority.Interactive)
        Read,Mutation->NetworkWorkContext("realtime",scoped?.priority ?: NetworkWorkPriority.Interactive,
            orderingKey=scoped?.orderingKey,isRetry=scoped?.isRetry ?: false)
    }
    companion object {
        fun of(envelope:Envelope):RealtimeFramePolicy=when(envelope.bodyCase) {
            CLIENT_HELLO, AUTHENTICATE -> Handshake
            PRESENCE_PUBLICATION_CONTROL, HEARTBEAT, SYNC_ACK, SNAPSHOT_ACK,
            AUTHOR_PRESENTATION_RECEIPT, AUTHOR_PRESENTATION_END, GROUP_EVENT_UNSUBSCRIBE, UNSUBSCRIBE_PRESENCE,
            UNSUBSCRIBE_TYPING -> Control
            SET_TYPING_STATE -> Ephemeral
            AUTHOR_PRESENTATION_START, SYNC_PULL, SYNC_SNAPSHOT, SNAPSHOT_PAGE_PULL,
            LIST_ROOM_MEMBERS, USER_ROOM_DIRECTORY_LIST, ROOM_SYNC_STATE_BATCH, ACCOUNT_ROOM_CHANGES_START,
            ROOM_LATEST_VISIBLE_BATCH, GROUP_EVENT_PULL_BATCH, GROUP_EVENT_PULL, GROUP_EVENT_SUBSCRIBE,
            LIST_READ_RECEIPT_READERS, SUBSCRIBE_PRESENCE, SUBSCRIBE_TYPING, GET_LIVE_ACTIVITY_PREFERENCES,
            GET_GROUP_ROLE_POLICY_BASELINE -> Read
            DEVICE_ROOM_PROGRESS_REPORT, RECORD_READ_RECEIPT, SET_CONVERSATION_STATE, SET_MESSAGE_FAVORITE,
            MESSAGE_SEND_OPERATION, MESSAGE_SEND_OPERATION_RECOVER -> Mutation
            DEVICE_ROOM_PROGRESS_RECORDED, REALTIME_COVERAGE, PRESENCE_PUBLICATION_CONTROLLED, SERVER_HELLO,
            AUTHENTICATED, HEARTBEAT_ACK, MESSAGE_ACCEPTED, MEMBERSHIP_CHANGED,
            MESSAGE_WITHDRAWN, MESSAGE_REACTION_CHANGED, MESSAGE_EDITED, SYNC_BATCH,
            RESET_REQUIRED, ACKNOWLEDGED, SNAPSHOT_MANIFEST, SNAPSHOT_PAGE,
            SYNC_AVAILABLE, READ_RECEIPT_RECORDED, ROOM_MEMBERS_PAGE, USER_ROOM_DIRECTORY_PAGE,
            ROOM_SYNC_STATE_BATCH_RESULT, ACCOUNT_ROOM_CHANGES_READY, ACCOUNT_ROOM_RESYNC_REQUIRED, ROOM_LATEST_VISIBLE_BATCH_RESULT,
            AUTHOR_PRESENTATION_DELTA, AUTHOR_PRESENTATION_ENDED, AUTHOR_PRESENTATION_RECEIPTED, AUTHOR_PRESENTATION_INTERESTS_RECEIVED,
            AUTHOR_PRESENTATION_STARTED, PERSONAL_PREFERENCE_RECEIPT, GROUP_EVENT_PAGE_BATCH, GROUP_EVENT_PAGE,
            GROUP_EVENT_SUBSCRIBED, GROUP_EVENT_AVAILABLE, STRANGER_MESSAGE_PERMISSION_SET, USER_ADD_PERMISSION_SET,
            READ_RECEIPT_PREFERENCES_SET, READ_RECEIPT_READERS_PAGE, LIVE_ACTIVITY_PREFERENCES_SET, PRESENCE_SUBSCRIBED,
            TYPING_STATE_CHANGED, PRESENCE_CHANGED, LIVE_ACTIVITY_PREFERENCES, CONVERSATION_STATE_SET,
            MESSAGE_FAVORITE_CHANGED, PINNED_MESSAGE_CHANGED, GROUP_ANNOUNCEMENT_CHANGED, GROUP_ROLE_PERMISSIONS_CHANGED,
            GROUP_MEMBER_ROLE_CHANGED, GROUP_ROLE_POLICY_BASELINE, RELATIONSHIP_CHANGED, USER_BLOCK_CHANGED,
            MEMBER_MUTED, MEMBER_REMOVED_BY_MODERATOR, MESSAGE_SEND_OPERATION_RESULT, ERROR -> ServerOnly
            AUTHOR_PRESENTATION_INTERESTS -> if(envelope.authorPresentationInterests.keysCount==0) Control else Read
            BODY_NOT_SET,null -> throw ClientFailure.Protocol()
        }
    }
}
