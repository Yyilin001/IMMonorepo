internal class MemoryGroups : GroupCreationStore {
    val works = mutableListOf<GroupCreationWork>()
    override suspend fun prepareGroup(command: GroupCreationCommand) = GroupCreationWork.fresh(command).also { works.add(it) }
    override suspend fun groupWorks() = works.toPersistentList()
    override suspend fun updateGroup(expected: GroupCreationWork, updated: GroupCreationWork) {
        val index = works.indexOf(expected); check(index >= 0); updated.progress?.validate(updated.command, expected.progress); works[index] = updated
    }
}
internal fun groupProof(command: GroupCreationCommand) = buildJsonObject { put("identity", command.identity()); put("fingerprint", fingerprintPayload(command.fingerprint)) }
internal fun groupProgress(command: GroupCreationCommand, count: Int, finalizing: Boolean = false, copied: Int = 0) = buildJsonObject {
    groupProof(command).forEach { (k, v) -> put(k, v) }; put("roomID", wireId("EEEEEEEE-EEEE-EEEE-EEEE-EEEEEEEEEEEE"))
    put("phase", if (finalizing) "finalizing" else "staging"); put("acceptedMemberCount", count); put("copiedMemberCount", copied)
    put("acceptedPrefixDigest", fingerprintPayload(command.audienceDigest(count)))
}
internal fun groupReceipt(command: GroupCreationCommand, closed: Boolean = false) = buildJsonObject {
    groupProof(command).forEach { (k, v) -> put(k, v) }; put("resolvedAtMilliseconds", 2000)
    put("outcome", buildJsonObject {
        if (closed) put("closed", buildJsonObject {})
        else put("created", buildJsonObject {
            put("roomID", wireId("EEEEEEEE-EEEE-EEEE-EEEE-EEEEEEEEEEEE")); put("title", command.title)
            put("capacityClass", command.capacity.wire); put("memberCount", command.members.size + 1)
        })
    })
}
private fun groupCommand(count: Int = 1) = GroupCreationCommand.create(actorId, " Test group ",
    (1..count).map { UserId("00000000-0000-0000-0000-%012d".format(it)) }.toPersistentList(), 1000)
class GroupCreationTests {
    @Test fun `Swift generated 513 member fingerprints match across the page boundary`() {
        // Generated by the repository's V2GroupCreationAudience/Intent/AppendRequest, not the Kotlin encoder.
        val command = groupCommand(513).copy(operation = "DDDDDDDD-DDDD-DDDD-DDDD-DDDDDDDDDDDD", deadlineMilliseconds = 601000)
        assertEquals("6Yu7Lfo7pnI9mlLFXZDhBLna8EsmHCerN5Ikj5RoHoU=", command.audienceDigest())
        assertEquals("KMfPLhS7z9y7doBSpYHP1B7VdWRXR/YTAssDJosDBLA=", command.audienceDigest(512))
        assertEquals("cCglpGbk9pW34ssiU8WC+tLZGUEnja0/6uYII8/L7Ys=", command.fingerprint)
        assertEquals("L2CCXTobpmn/WeVSJ8NvRXHdUMC3El1XvYxIcEbMjig=", command.page(0).objectValue("pageFingerprint").string("digest"))
        assertEquals("94ToTMinj1QTDnOPT3jPl+lw3R5eWc1hJHI6Wtz+YLw=", command.page(512).objectValue("pageFingerprint").string("digest"))
    }
    @Test fun `frozen canonical audience uses complete bounded pages and preserves immutable serialization`() {
        val command = groupCommand(513)
        assertEquals("Test group", command.title)
        assertEquals(512, command.page(0)["memberUserIDs"]!!.jsonArray.size)
        assertEquals(1, command.page(512)["memberUserIDs"]!!.jsonArray.size)
        assertNotEquals(command.page(0)["pageFingerprint"], command.page(512)["pageFingerprint"])
        assertFailsWith<IllegalArgumentException> { command.page(1) }
        assertFailsWith<IllegalArgumentException> { command.copy(members = persistentListOf(targetId, targetId)) }
        assertFailsWith<IllegalArgumentException> { command.copy(members = persistentListOf(actorId)) }
        assertFailsWith<IllegalArgumentException> { command.copy(title = "a\u0000b") }
        assertFailsWith<IllegalArgumentException> { command.copy(title = "界".repeat(41)) }
        assertEquals(command, Json.decodeFromString<GroupCreationCommand>(Json.encodeToString(command)))
        assertEquals(GroupCapacity.Standard, groupCommand(4999).capacity)
        assertEquals(GroupCapacity.Large, groupCommand(5000).capacity)
    }
    @Test fun `progress binds the exact accepted prefix room phase and monotonic counters`() = runTest {
        val command = groupCommand(513)
        val client = GroupCreationClient(FakeEdge { _, _ -> EdgeResponse(200, directResult("progress", groupProgress(command, 512))) })
        val progress = (client.execute(command, null, false, false) as GroupCreationResult.Progress).value
        progress.validate(command)
        assertFailsWith<ClientFailure.Protocol> { progress.copy(prefixDigest = command.audienceDigest(513)).validate(command) }
        assertFailsWith<ClientFailure.Protocol> { progress.copy(accepted = 511).validate(command) }
        assertFailsWith<ClientFailure.Protocol> { progress.copy(phase = GroupCreationPhase.Finalizing).validate(command) }
        assertFailsWith<ClientFailure.Protocol> { progress.copy(room = RoomId(UUID.randomUUID().toString())).validate(command, progress) }
        val complete = progress.copy(accepted = 513, prefixDigest = command.audienceDigest(), phase = GroupCreationPhase.Finalizing, copied = 512)
        complete.validate(command, progress)
        assertFailsWith<ClientFailure.Protocol> { progress.validate(command, complete) }
    }
    @Test fun `begin append finalize recovery advances one page and only final receipt completes`() = runTest {
        val store = MemoryGroups(); var now = 1000L
        val command = groupCommand(513); store.prepareGroup(command)
        val paths = mutableListOf<String>()
        val api = FakeEdge { path, body ->
            assertTrue(store.works.single().reconcile) // Uncertainty journal precedes any network call.
            val intent=requireNotNull(currentCoroutineContext()[NetworkWorkIntent]);assertFalse(intent.isRetry)
            assertEquals(if(paths.isEmpty()) NetworkWorkPriority.Interactive else NetworkWorkPriority.Recovery,intent.priority)
            paths.add(path)
            val result = when (paths.size) {
                1 -> { assertTrue(path.endsWith("begin")); directResult("progress", groupProgress(command, 0)) }
                2 -> { assertTrue(path.endsWith("append")); assertEquals(0, body!!.number("offset")); directResult("progress", groupProgress(command, 512)) }
                3 -> { assertTrue(path.endsWith("append")); assertEquals(512, body!!.number("offset")); directResult("progress", groupProgress(command, 513)) }
                4 -> { assertTrue(path.endsWith("finalize")); directResult("progress", groupProgress(command, 513, true, 512)) }
                else -> { assertTrue(path.endsWith("operations/recover")); assertEquals("query", body!!.string("action")); directResult("receipt", groupReceipt(command)) }
            }
            EdgeResponse(200, result)
        }
        val service = GroupCreationService(actorId, GroupCreationClient(api), store, { now }, { now * 1_000_000 })
        repeat(4) { service.flush(); assertFalse(store.works.single().terminal); now += 1000 }
        service.flush(); assertEquals(GroupCreationStatus.Created, store.works.single().status); assertEquals(5, paths.size)
    }
    @Test fun `interrupted submission survives restart and reconciles before another write`() = runTest {
        val store = MemoryGroups(); val command = groupCommand(); store.prepareGroup(command); var now = 1000L
        val api = FakeEdge { _, _ -> assertCommandAttempt(false);throw CancellationException() }
        fun service() = GroupCreationService(actorId, GroupCreationClient(api), store, { now }, { 0 })
        assertFailsWith<CancellationException> { service().flush() }; assertTrue(store.works.single().reconcile);assertEquals(true,store.works.single().retryRequired)
        store.works[0]=Json.decodeFromString<GroupCreationWork>(Json.encodeToString(GroupCreationWork.serializer(),store.works.single()))
        service().retry(command.operation)
        api.answer = { path, body -> assertCommandAttempt(true); assertTrue(path.endsWith("recover")); assertEquals("query", body!!.string("action")); EdgeResponse(200, directResult("progress", groupProgress(command, 0))) }
        service().flush(); assertFalse(store.works.single().reconcile)
        api.answer = { path, _ -> val intent=requireNotNull(currentCoroutineContext()[NetworkWorkIntent]);assertFalse(intent.isRetry);assertEquals(NetworkWorkPriority.Recovery,intent.priority); assertTrue(path.endsWith("append")); throw IOException() }
        service().flush(); assertTrue(store.works.single().reconcile); assertEquals(command, store.works.single().command)
        now = 700_000
        api.answer = { path, body -> assertCommandAttempt(true); assertTrue(path.endsWith("recover")); assertEquals("closeIfAbsent", body!!.string("action")); EdgeResponse(200, directResult("receipt", groupReceipt(command, true))) }
        service().flush(); assertEquals(GroupCreationStatus.Closed, store.works.single().status)
    }
    @Test fun `cancellation records intent and an already created room remains a created result`() = runTest {
        val store = MemoryGroups(); val command = groupCommand(); store.prepareGroup(command)
        val api = FakeEdge { path, body -> assertTrue(path.endsWith("recover")); assertEquals("closeIfAbsent", body!!.string("action")); EdgeResponse(200, directResult("receipt", groupReceipt(command))) }
        val service = GroupCreationService(actorId, GroupCreationClient(api), store, { 1000 }, { 0 })
        service.cancel(command.operation); assertTrue(store.works.single().cancellationRequested)
        service.flush(); assertEquals(GroupCreationStatus.Created, store.works.single().status)
    }
    @Test fun `identical progress exhausts retries while forward progress renews only step budget`() = runTest {
        val store = MemoryGroups(); val command = groupCommand(); store.prepareGroup(command); var now = 1000L
        val api = FakeEdge { _, _ -> EdgeResponse(200, directResult("progress", groupProgress(command, 0))) }
        val service = GroupCreationService(actorId, GroupCreationClient(api), store, { now }, { 0 })
        repeat(13) { service.flush(); now += 1000 }
        assertEquals(GroupCreationStatus.NeedsAttention, store.works.single().status)
        assertEquals(command.deadlineMilliseconds, store.works.single().command.deadlineMilliseconds)
        service.retry(command.operation)
        api.answer = { _, _ -> EdgeResponse(200, directResult("progress", groupProgress(command, 1))) }
        service.flush(); assertEquals(0, store.works.single().attempts)
    }
    @Test fun `foreign receipt or mismatched created title cannot complete the original intent`() {
        val command = groupCommand()
        assertFailsWith<ClientFailure.Protocol> { GroupCreationClient.decodeReceipt(command, groupReceipt(groupCommand())) }
        val receipt = groupReceipt(command)
        val wrong = JsonObject(receipt + ("outcome" to groupReceipt(command.copy(title = "other")).getValue("outcome")))
        assertFailsWith<ClientFailure.Protocol> { GroupCreationClient.decodeReceipt(command, wrong) }
    }
    @Test fun `wall clock rollback before first dispatch cannot extend the original click window`() = runTest {
        val store = MemoryGroups(); var wall = 1000L; var nanos = 0L
        val api = FakeEdge { path, body ->
            assertTrue(path.endsWith("recover")); assertEquals("closeIfAbsent", body!!.string("action"))
            EdgeResponse(200, directResult("receipt", groupReceipt(store.works.single().command, true)))
        }
        val service = GroupCreationService(actorId, GroupCreationClient(api), store, { wall }, { nanos })
        service.prepare("group", persistentListOf())
        wall = 500; nanos = 601_000_000_000
        service.flush(); assertEquals(GroupCreationStatus.Closed, store.works.single().status)
    }
}
