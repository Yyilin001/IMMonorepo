#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

ONLINE_LADDER="${ONLINE_LADDER:-1000 2000 3000}"
MESSAGE_RATES="${MESSAGE_RATES:-10 50 100}"
MESSAGE_HOLD_SECONDS="${MESSAGE_HOLD_SECONDS:-600}"
MESSAGE_CONNECT_RAMP_SECONDS="${MESSAGE_CONNECT_RAMP_SECONDS:-300}"
MESSAGE_TIMEOUT_SECONDS="${MESSAGE_TIMEOUT_SECONDS:-30}"
MESSAGE_HEARTBEAT_INTERVAL_SECONDS="${MESSAGE_HEARTBEAT_INTERVAL_SECONDS:-15}"
MESSAGE_CONNECTION_QUEUE_POOL_SIZE="${MESSAGE_CONNECTION_QUEUE_POOL_SIZE:-256}"
MESSAGE_MAX_RECONNECTS="${MESSAGE_MAX_RECONNECTS:-0}"
MESSAGE_CONNECTION_LOG_DIR="${MESSAGE_CONNECTION_LOG_DIR:-/tmp/imtcp-driver-logs-message-send}"
MESSAGE_LOGIN_CACHE_DIR="${MESSAGE_LOGIN_CACHE_DIR:-/tmp/imtcp-login-cache-message-send}"
MESSAGE_SENDER_EVERY="${MESSAGE_SENDER_EVERY:-1}"
MESSAGE_RECEIVER_OFFSET="${MESSAGE_RECEIVER_OFFSET:-1}"
MESSAGE_ACTIVE_CONVERSATION_USERS="${MESSAGE_ACTIVE_CONVERSATION_USERS:-${ACTIVE_CONVERSATION_USERS:-0}}"
MESSAGE_COOLDOWN_SECONDS="${MESSAGE_COOLDOWN_SECONDS:-30}"
MESSAGE_COMPLETION_MODE="${MESSAGE_COMPLETION_MODE:-full}"
MESSAGE_GLOBAL_HOLD_BARRIER_MIN_RATIO="${MESSAGE_GLOBAL_HOLD_BARRIER_MIN_RATIO:-1.0}"
MESSAGE_PREWARM_LOGIN_CACHE="${MESSAGE_PREWARM_LOGIN_CACHE:-${PREWARM_LOGIN_CACHE:-true}}"
MESSAGE_REQUIRE_LOGIN_CACHE="${MESSAGE_REQUIRE_LOGIN_CACHE:-${REQUIRE_LOGIN_CACHE:-true}}"
MESSAGE_METRICS_GATE_MODE="${MESSAGE_METRICS_GATE_MODE:-${IM_METRICS_GATE_MODE:-fail}}"
MESSAGE_COLLECT_REMOTE_METRICS="${MESSAGE_COLLECT_REMOTE_METRICS:-${COLLECT_REMOTE_METRICS:-true}}"
MESSAGE_COLLECT_IM_METRICS="${MESSAGE_COLLECT_IM_METRICS:-${COLLECT_IM_METRICS:-true}}"
MESSAGE_COLLECT_IM_METRICS_DELTA="${MESSAGE_COLLECT_IM_METRICS_DELTA:-${COLLECT_IM_METRICS_DELTA:-true}}"
MESSAGE_SEND_LADDER_DRY_RUN="${MESSAGE_SEND_LADDER_DRY_RUN:-false}"

bool_enabled() {
  case "${1:-}" in
    1|true|TRUE|yes|YES|on|ON) return 0 ;;
    *) return 1 ;;
  esac
}

if [[ -z "${IM_CONVERSATION_ID:-}" ]]; then
  echo "IM_CONVERSATION_ID is required." >&2
  exit 1
fi
if [[ -z "${ACCOUNT_FILE:-}" ]]; then
  echo "ACCOUNT_FILE is required." >&2
  exit 1
fi

mkdir -p "${MESSAGE_CONNECTION_LOG_DIR}" "${MESSAGE_LOGIN_CACHE_DIR}"

for connections in ${ONLINE_LADDER}; do
  for rate in ${MESSAGE_RATES}; do
    echo
    echo "== TCP message-send step: connections=${connections}, rate=${rate} msg/s, hold=${MESSAGE_HOLD_SECONDS}s =="
    step_login_cache_dir="${MESSAGE_LOGIN_CACHE_DIR}/rate-${rate}"
    step_connection_log_dir="${MESSAGE_CONNECTION_LOG_DIR}/connections-${connections}-rate-${rate}"
    if bool_enabled "${MESSAGE_SEND_LADDER_DRY_RUN}"; then
      printf 'dry-run tcp_capacity_ladder LADDER=%s MESSAGE_RATE_PER_SECOND=%s MESSAGE_PROFILE=pair-delivery IM_TCP_MESSAGE_COMPLETION_MODE=%s PREWARM_LOGIN_CACHE=%s REQUIRE_LOGIN_CACHE=%s IM_METRICS_GATE_MODE=%s COLLECT_REMOTE_METRICS=%s COLLECT_IM_METRICS=%s COLLECT_IM_METRICS_DELTA=%s LOGIN_CACHE_DIR=%s CONNECTION_LOG_DIR=%s\n' \
        "${connections}" \
        "${rate}" \
        "${MESSAGE_COMPLETION_MODE}" \
        "${MESSAGE_PREWARM_LOGIN_CACHE}" \
        "${MESSAGE_REQUIRE_LOGIN_CACHE}" \
        "${MESSAGE_METRICS_GATE_MODE}" \
        "${MESSAGE_COLLECT_REMOTE_METRICS}" \
        "${MESSAGE_COLLECT_IM_METRICS}" \
        "${MESSAGE_COLLECT_IM_METRICS_DELTA}" \
        "${step_login_cache_dir}" \
        "${step_connection_log_dir}"
      continue
    fi
    LADDER="${connections}" \
      MESSAGES=1 \
      MESSAGE_PROFILE=pair-delivery \
      IM_TCP_MESSAGE_COMPLETION_MODE="${MESSAGE_COMPLETION_MODE}" \
      MESSAGE_RATE_PER_SECOND="${rate}" \
      MESSAGE_SENDER_EVERY="${MESSAGE_SENDER_EVERY}" \
      MESSAGE_RECEIVER_OFFSET="${MESSAGE_RECEIVER_OFFSET}" \
      ACTIVE_CONVERSATION_USERS="${MESSAGE_ACTIVE_CONVERSATION_USERS}" \
      GLOBAL_HOLD_BARRIER_MIN_RATIO="${MESSAGE_GLOBAL_HOLD_BARRIER_MIN_RATIO}" \
      HOLD_SECONDS="${MESSAGE_HOLD_SECONDS}" \
      CONNECT_RAMP_SECONDS="${MESSAGE_CONNECT_RAMP_SECONDS}" \
      TIMEOUT_SECONDS="${MESSAGE_TIMEOUT_SECONDS}" \
      HEARTBEAT_INTERVAL_SECONDS="${MESSAGE_HEARTBEAT_INTERVAL_SECONDS}" \
      HEARTBEAT_LOG_MODE="${HEARTBEAT_LOG_MODE:-errors}" \
      CONNECTION_QUEUE_POOL_SIZE="${MESSAGE_CONNECTION_QUEUE_POOL_SIZE}" \
      MAX_RECONNECTS="${MESSAGE_MAX_RECONNECTS}" \
      PREWARM_LOGIN_CACHE="${MESSAGE_PREWARM_LOGIN_CACHE}" \
      REQUIRE_LOGIN_CACHE="${MESSAGE_REQUIRE_LOGIN_CACHE}" \
      LOGIN_CACHE_DIR="${step_login_cache_dir}" \
      LOGIN_CACHE_FILE="${MESSAGE_LOGIN_CACHE_FILE:-${LOGIN_CACHE_FILE:-}}" \
      LOGIN_CACHE_TTL_GUARD_SECONDS="${LOGIN_CACHE_TTL_GUARD_SECONDS:-60}" \
      LOGIN_MODE="${LOGIN_MODE:-upfront}" \
      CONNECTION_LOG_DIR="${step_connection_log_dir}" \
      COLLECT_REMOTE_METRICS="${MESSAGE_COLLECT_REMOTE_METRICS}" \
      COLLECT_IM_METRICS="${MESSAGE_COLLECT_IM_METRICS}" \
      COLLECT_IM_METRICS_DELTA="${MESSAGE_COLLECT_IM_METRICS_DELTA}" \
      IM_METRICS_GATE_MODE="${MESSAGE_METRICS_GATE_MODE}" \
      COOLDOWN_SECONDS="${MESSAGE_COOLDOWN_SECONDS}" \
      "${SCRIPT_DIR}/tcp_capacity_ladder.sh"
  done
done
