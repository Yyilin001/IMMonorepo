#!/bin/zsh

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

NODE_ID="${1:-im-api-1}"
HTTP_PORT="${2:-8080}"
TCP_PORT="${3:-9000}"

cd "$PROJECT_ROOT"

if [[ -f ".env.local" ]]; then
  set -a
  source ".env.local"
  set +a
fi

export DATABASE_HOST="${DATABASE_HOST:-127.0.0.1}"
export DATABASE_PORT="${DATABASE_PORT:-5432}"
export DATABASE_NAME="${DATABASE_NAME:-vapor_auth}"
export DATABASE_USERNAME="${DATABASE_USERNAME:-$(whoami)}"
export DATABASE_PASSWORD="${DATABASE_PASSWORD:-}"
export DATABASE_PRIMARY_HOST="${DATABASE_PRIMARY_HOST:-$DATABASE_HOST}"
export DATABASE_PRIMARY_PORT="${DATABASE_PRIMARY_PORT:-$DATABASE_PORT}"
export DATABASE_PRIMARY_NAME="${DATABASE_PRIMARY_NAME:-$DATABASE_NAME}"
export DATABASE_PRIMARY_USERNAME="${DATABASE_PRIMARY_USERNAME:-$DATABASE_USERNAME}"
export DATABASE_PRIMARY_PASSWORD="${DATABASE_PRIMARY_PASSWORD:-$DATABASE_PASSWORD}"
export DATABASE_REPLICA_HOST="${DATABASE_REPLICA_HOST:-$DATABASE_HOST}"
export DATABASE_REPLICA_PORT="${DATABASE_REPLICA_PORT:-$DATABASE_PORT}"
export DATABASE_REPLICA_NAME="${DATABASE_REPLICA_NAME:-$DATABASE_NAME}"
export DATABASE_REPLICA_USERNAME="${DATABASE_REPLICA_USERNAME:-$DATABASE_USERNAME}"
export DATABASE_REPLICA_PASSWORD="${DATABASE_REPLICA_PASSWORD:-$DATABASE_PASSWORD}"
export REDIS_URL="${REDIS_URL:-redis://127.0.0.1:6379}"
export IM_ROUTING_MODE="redis"
export IM_NODE_ID="$NODE_ID"
export PORT="$HTTP_PORT"
export IM_TCP_PORT="$TCP_PORT"
export IM_OUTBOX_BATCH_SIZE="${IM_OUTBOX_BATCH_SIZE:-100}"
export IM_OUTBOX_POLL_INTERVAL_MS="${IM_OUTBOX_POLL_INTERVAL_MS:-250}"
export IM_OUTBOX_MAX_RETRIES="${IM_OUTBOX_MAX_RETRIES:-5}"
export MEDIA_STORAGE_PROVIDER="${MEDIA_STORAGE_PROVIDER:-local}"
export JWT_SECRET="${JWT_SECRET:-dev-jwt-secret-change-me}"
export SEED_USER_EMAIL="${SEED_USER_EMAIL:-demo@example.com}"
export SEED_USER_PASSWORD="${SEED_USER_PASSWORD:-password1234}"

cat <<EOF
Starting IMServer node:
  IM_NODE_ID=$IM_NODE_ID
  PORT=$PORT
  IM_TCP_PORT=$IM_TCP_PORT
  REDIS_URL=$REDIS_URL
  DATABASE_PRIMARY_HOST=$DATABASE_PRIMARY_HOST
  DATABASE_REPLICA_HOST=$DATABASE_REPLICA_HOST
  MEDIA_STORAGE_PROVIDER=$MEDIA_STORAGE_PROVIDER
EOF

exec swift run IMServer
