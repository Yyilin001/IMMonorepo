release_deploy_lock() {
  if [[ -d "${IM_DEPLOY_LOCK_DIR}" && -f "${IM_DEPLOY_LOCK_DIR}/pid" ]] \
    && [[ "$(cat "${IM_DEPLOY_LOCK_DIR}/pid" 2>/dev/null || true)" == "$$" ]]; then
    rm -rf "${IM_DEPLOY_LOCK_DIR}"
  fi
}

acquire_deploy_lock() {
  if bool_enabled "${IM_DEPLOY_DISABLE_LOCK}"; then
    echo "Skipping deploy lock because IM_DEPLOY_DISABLE_LOCK=${IM_DEPLOY_DISABLE_LOCK}."
    return 0
  fi

  install -d -m 0755 "$(dirname "${IM_DEPLOY_LOCK_DIR}")"
  if mkdir -m 0700 "${IM_DEPLOY_LOCK_DIR}" 2>/dev/null; then
    {
      printf 'pid=%s\n' "$$"
      printf 'startedAt=%s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
      printf 'user=%s\n' "$(id -un 2>/dev/null || true)"
      printf 'cwd=%s\n' "$(pwd)"
    } >"${IM_DEPLOY_LOCK_DIR}/info"
    printf '%s\n' "$$" >"${IM_DEPLOY_LOCK_DIR}/pid"
    chmod 0600 "${IM_DEPLOY_LOCK_DIR}/info" "${IM_DEPLOY_LOCK_DIR}/pid"
    trap release_deploy_lock EXIT
    trap 'release_deploy_lock; exit 130' INT
    trap 'release_deploy_lock; exit 143' TERM
    return 0
  fi

  local lock_mtime now age
  lock_mtime="$(stat -c %Y "${IM_DEPLOY_LOCK_DIR}" 2>/dev/null || printf '0')"
  now="$(date +%s)"
  age=$((now - lock_mtime))
  if (( lock_mtime > 0 && age > IM_DEPLOY_LOCK_STALE_SECONDS )); then
    echo "Removing stale deploy lock ${IM_DEPLOY_LOCK_DIR} ageSeconds=${age}." >&2
    rm -rf "${IM_DEPLOY_LOCK_DIR}"
    acquire_deploy_lock
    return
  fi

  echo "Another deploy appears to be running; lock=${IM_DEPLOY_LOCK_DIR}" >&2
  if [[ -f "${IM_DEPLOY_LOCK_DIR}/info" ]]; then
    sed 's/^/  /' "${IM_DEPLOY_LOCK_DIR}/info" >&2 || true
  fi
  echo "Set IM_DEPLOY_DISABLE_LOCK=true only if you have verified the stale lock manually." >&2
  exit 1
}

