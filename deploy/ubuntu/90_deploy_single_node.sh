validate_final_audit_public_targets() {
  local public_base_url_scheme public_base_url_host public_base_url_host_reason
  local expect_base_url_scheme expect_base_url_host expect_base_url_host_reason
  local public_base_url_port expect_base_url_port
  local expect_tcp_host_reason insecure_public_base_url_override
  if ! bool_enabled "${IM_DEPLOY_FINAL_AUDIT_REQUIRE_PERFORMANCE_GATE_EFFECTIVE}"; then
    return 0
  fi
  if [[ -z "${IM_DEPLOY_FINAL_AUDIT_PUBLIC_BASE_URL_EFFECTIVE}" ]]; then
    printf 'deploy result=fail reason=final_audit_public_base_url_missing appEnv=%s requirePerformanceGate=%s hint=set_PUBLIC_BASE_URL_or_IM_PUBLIC_BASE_URL\n' \
      "$(deploy_app_env)" \
      "${IM_DEPLOY_FINAL_AUDIT_REQUIRE_PERFORMANCE_GATE_EFFECTIVE}" >&2
    return 2
  fi
  public_base_url_scheme="$(deploy_scheme_from_url "${IM_DEPLOY_FINAL_AUDIT_PUBLIC_BASE_URL_EFFECTIVE}")"
  if [[ "${public_base_url_scheme}" != "https" ]]; then
    printf 'deploy result=fail reason=final_audit_public_base_url_https_required publicBaseURL=%s hint=set_PUBLIC_BASE_URL_or_IM_PUBLIC_BASE_URL_to_https_or_disable_gate_for_first_bootstrap\n' \
      "${IM_DEPLOY_FINAL_AUDIT_PUBLIC_BASE_URL_EFFECTIVE}" >&2
    return 2
  fi
  public_base_url_port="$(deploy_port_from_url "${IM_DEPLOY_FINAL_AUDIT_PUBLIC_BASE_URL_EFFECTIVE}")"
  if [[ -n "${public_base_url_port}" && "${public_base_url_port}" != "443" ]]; then
    printf 'deploy result=fail reason=final_audit_public_base_url_default_https_port_required publicBaseURL=%s port=%s hint=use_default_https_443_for_long_term_production\n' \
      "${IM_DEPLOY_FINAL_AUDIT_PUBLIC_BASE_URL_EFFECTIVE}" \
      "${public_base_url_port}" >&2
    return 2
  fi
  public_base_url_host="$(deploy_host_from_url "${IM_DEPLOY_FINAL_AUDIT_PUBLIC_BASE_URL_EFFECTIVE}")"
  public_base_url_host_reason="$(deploy_public_host_policy_reason "${public_base_url_host}")"
  if [[ "${public_base_url_host_reason}" != "ok" ]]; then
    printf 'deploy result=fail reason=final_audit_public_base_url_domain_required publicBaseURL=%s host=%s hostReason=%s hint=use_a_real_production_domain_not_a_raw_ip_or_placeholder\n' \
      "${IM_DEPLOY_FINAL_AUDIT_PUBLIC_BASE_URL_EFFECTIVE}" \
      "${public_base_url_host:-<empty>}" \
      "${public_base_url_host_reason}" >&2
    return 2
  fi
  if [[ -z "${IM_DEPLOY_FINAL_AUDIT_PERFORMANCE_GATE_EXPECT_BASE_URL_EFFECTIVE}" ]]; then
    printf 'deploy result=fail reason=final_audit_expect_base_url_missing hint=set_IM_DEPLOY_FINAL_AUDIT_PERFORMANCE_GATE_EXPECT_BASE_URL_or_PUBLIC_BASE_URL\n' >&2
    return 2
  fi
