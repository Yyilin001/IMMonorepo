bool_enabled() {
  case "${1:-}" in
    1|true|TRUE|yes|YES|on|ON) return 0 ;;
    *) return 1 ;;
  esac
}

ensure_deploy_file_parent_dir() {
  local path="$1"
  [[ -n "${path}" ]] || return 0
  install -d -m 0750 "$(dirname "${path}")"
}

update_deploy_latest_symlink() {
  local target="$1"
  local link="$2"
  local tmp
  [[ -n "${target}" && -n "${link}" ]] || return 0
  if [[ -e "${link}" && ! -L "${link}" ]]; then
    printf 'deploy result=fail reason=latest_link_path_not_symlink path=%s\n' "${link}" >&2
    return 2
  fi
  ensure_deploy_file_parent_dir "${link}"
  tmp="${link}.tmp.$$"
  rm -f "${tmp}"
  ln -s "${target}" "${tmp}"
  mv -f "${tmp}" "${link}"
  printf 'deploy latest-evidence result=pass link=%s target=%s\n' "${link}" "${target}"
}

update_deploy_repair_latest_symlinks_if_verified() {
  if ! bool_enabled "${IM_DEPLOY_REPAIR_ALIYUN_SECURITY_GROUP_APPLY}"; then
    printf 'deploy latest-evidence result=skip reason=repair_not_applied apply=%s receipt=%s\n' \
      "${IM_DEPLOY_REPAIR_ALIYUN_SECURITY_GROUP_APPLY}" \
      "${IM_DEPLOY_REPAIR_ALIYUN_SECURITY_GROUP_RECEIPT_JSON}"
    return 0
  fi
  update_deploy_latest_symlink "${IM_DEPLOY_ALIYUN_SECURITY_GROUP_OUTPUT}" "${IM_DEPLOY_ALIYUN_SECURITY_GROUP_LATEST_SNAPSHOT_LINK}"
  update_deploy_latest_symlink "${IM_DEPLOY_REPAIR_ALIYUN_SECURITY_GROUP_PLAN_JSON}" "${IM_DEPLOY_REPAIR_ALIYUN_SECURITY_GROUP_LATEST_PLAN_LINK}"
