-- `messages_room_id_room_sequence_key` duplicates the accepted-message
-- invariant already enforced by
-- `room_events_room_id_room_sequence_event_type_key`:
--
--   * every accepted message is inserted with exactly one `message.accepted`
--     room event in the same transaction;
--   * both rows carry the same (room_id, room_sequence); and
--   * room-event uniqueness rejects another accepted message event at that
--     sequence.
--
-- No read path constrains `messages` by `(room_id, room_sequence)`; timeline
-- reads use `messages_room_timeline_sequence_key`, while event pulls use the
-- room-events uniqueness index.  Retaining both indexes writes the same room
-- sequence key twice for every accepted message.
--
-- PostgreSQL does not support DROP CONSTRAINT CONCURRENTLY. Run this short
-- metadata operation in a controlled migration window, after verifying the
-- invariant above for the deployed writer version. The accompanying schema
-- contract test protects fresh installs.
ALTER TABLE im_v2.messages
    DROP CONSTRAINT IF EXISTS messages_room_id_room_sequence_key;
