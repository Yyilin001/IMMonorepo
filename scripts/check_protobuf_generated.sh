#!/usr/bin/env bash
set -Eeuo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PROTO_DIR="${ROOT_DIR}/Protocol/im_realtime/v1"
PROTO_FILE="${PROTO_DIR}/im_realtime.proto"
PROTOCOL_VERSION_FILE="${PROTO_DIR}/protocol_version.txt"
CLIENT_GENERATED_DIR="${ROOT_DIR}/IMClientKit/Sources/IMClientKit/Generated"
SERVER_GENERATED_DIR="${ROOT_DIR}/IMServer/Sources/IMServer/Generated"
CLIENT_PROTOBUF_DIR="${CLIENT_GENERATED_DIR}/Protobuf"
SERVER_PROTOBUF_DIR="${SERVER_GENERATED_DIR}/Protobuf"
SWIFT_PROTOBUF_CHECKOUT="${ROOT_DIR}/IMServer/.build/checkouts/swift-protobuf"

fail() {
  echo "protobuf generated check failed: $1" >&2
  exit 1
}

require_file() {
  local file="$1"
  [[ -f "${file}" ]] || fail "required file is missing: ${file}"
}

require_dir() {
  local dir="$1"
  [[ -d "${dir}" ]] || fail "required directory is missing: ${dir}"
}

resolve_protoc_gen_swift() {
  if [[ -n "${PROTOC_GEN_SWIFT:-}" ]]; then
    [[ -x "${PROTOC_GEN_SWIFT}" ]] || fail "PROTOC_GEN_SWIFT is not executable: ${PROTOC_GEN_SWIFT}"
    printf '%s' "${PROTOC_GEN_SWIFT}"
    return 0
  fi

  if [[ ! -d "${SWIFT_PROTOBUF_CHECKOUT}" ]]; then
    swift package --package-path "${ROOT_DIR}/IMServer" resolve >/dev/null
  fi
  [[ -d "${SWIFT_PROTOBUF_CHECKOUT}" ]] || fail "swift-protobuf checkout is missing after SwiftPM resolve"

  swift build \
    --package-path "${SWIFT_PROTOBUF_CHECKOUT}" \
    -c release \
    --product protoc-gen-swift >/dev/null

  local built
  built="$(find "${SWIFT_PROTOBUF_CHECKOUT}/.build" -path "*/release/protoc-gen-swift" -type f | sort | head -n 1)"
  [[ -n "${built}" && -x "${built}" ]] || fail "unable to locate built protoc-gen-swift under ${SWIFT_PROTOBUF_CHECKOUT}/.build"
  printf '%s' "${built}"
}

write_protocol_version_file() {
  local target="$1"
  local version="$2"
  cat > "${target}" <<SWIFT
// Generated by scripts/generate_protobuf.sh. Do not edit manually.

public enum IMRealtimeProtocolVersion {
    public static let current: UInt32 = ${version}
    public static let currentInt: Int = ${version}
}
SWIFT
}

compare_dir() {
  local expected="$1"
  local actual="$2"
  local label="$3"
  if ! diff -ru "${actual}" "${expected}"; then
    fail "${label} generated files are stale. Run scripts/generate_protobuf.sh and commit the generated changes."
  fi
}

command -v protoc >/dev/null 2>&1 || fail "protoc is required. Install protobuf compiler, then rerun."
require_file "${PROTO_FILE}"
require_file "${PROTOCOL_VERSION_FILE}"
require_dir "${CLIENT_PROTOBUF_DIR}"
require_dir "${SERVER_PROTOBUF_DIR}"

PROTOCOL_VERSION="$(tr -d '[:space:]' < "${PROTOCOL_VERSION_FILE}")"
[[ "${PROTOCOL_VERSION}" =~ ^[0-9]+$ ]] || fail "protocol_version.txt must contain an integer"
PROTOC_GEN_SWIFT_BIN="$(resolve_protoc_gen_swift)"

TMP_DIR="$(mktemp -d)"
trap 'rm -rf "${TMP_DIR}"' EXIT

EXPECTED_CLIENT_PROTOBUF="${TMP_DIR}/client/Protobuf"
EXPECTED_SERVER_PROTOBUF="${TMP_DIR}/server/Protobuf"
EXPECTED_CLIENT_GENERATED="${TMP_DIR}/client"
EXPECTED_SERVER_GENERATED="${TMP_DIR}/server"
mkdir -p "${EXPECTED_CLIENT_PROTOBUF}" "${EXPECTED_SERVER_PROTOBUF}"

protoc \
  --plugin="protoc-gen-swift=${PROTOC_GEN_SWIFT_BIN}" \
  --proto_path="${ROOT_DIR}/Protocol" \
  --swift_out="${EXPECTED_CLIENT_PROTOBUF}" \
  "${PROTO_FILE}"

protoc \
  --plugin="protoc-gen-swift=${PROTOC_GEN_SWIFT_BIN}" \
  --proto_path="${ROOT_DIR}/Protocol" \
  --swift_out="${EXPECTED_SERVER_PROTOBUF}" \
  "${PROTO_FILE}"

write_protocol_version_file "${EXPECTED_CLIENT_GENERATED}/IMRealtimeProtocolVersion.swift" "${PROTOCOL_VERSION}"
write_protocol_version_file "${EXPECTED_SERVER_GENERATED}/IMRealtimeProtocolVersion.swift" "${PROTOCOL_VERSION}"

compare_dir "${EXPECTED_CLIENT_PROTOBUF}" "${CLIENT_PROTOBUF_DIR}" "IMClientKit protobuf"
compare_dir "${EXPECTED_SERVER_PROTOBUF}" "${SERVER_PROTOBUF_DIR}" "IMServer protobuf"
compare_dir "${EXPECTED_CLIENT_GENERATED}/IMRealtimeProtocolVersion.swift" "${CLIENT_GENERATED_DIR}/IMRealtimeProtocolVersion.swift" "IMClientKit protocol version"
compare_dir "${EXPECTED_SERVER_GENERATED}/IMRealtimeProtocolVersion.swift" "${SERVER_GENERATED_DIR}/IMRealtimeProtocolVersion.swift" "IMServer protocol version"

echo "protobuf generated check passed."
