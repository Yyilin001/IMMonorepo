#!/usr/bin/env bash
set -Eeuo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PROTO_DIR="$ROOT_DIR/Protocol/im_realtime/v2"
PROTO_FILE="$PROTO_DIR/im_v2.proto"
CLIENT_OUT="${V2_PROTOBUF_CLIENT_OUT:-$ROOT_DIR/IMV2ClientKit/Sources/IMV2ClientKit/Generated/Protobuf}"
SERVER_OUT="${V2_PROTOBUF_SERVER_OUT:-$ROOT_DIR/IMV2Server/Sources/IMV2Server/Generated/Protobuf}"
CLIENT_VERSION="${V2_PROTOBUF_CLIENT_VERSION:-$ROOT_DIR/IMV2ClientKit/Sources/IMV2ClientKit/Generated/IMV2ProtocolVersion.swift}"
SERVER_VERSION="${V2_PROTOBUF_SERVER_VERSION:-$ROOT_DIR/IMV2Server/Sources/IMV2Server/Generated/IMV2ProtocolVersion.swift}"
SWIFT_PROTOBUF_CHECKOUT="$ROOT_DIR/IMV2Server/.build/checkouts/swift-protobuf"
SWIFT_PROTOBUF_PLUGIN_SCRATCH_PATH="${V2_PROTOBUF_PLUGIN_SCRATCH_PATH:-}"

fail() { echo "generate V2 protobuf failed: $1" >&2; exit 1; }

resolve_plugin() {
  if [[ -n "${PROTOC_GEN_SWIFT:-}" ]]; then
    [[ -x "$PROTOC_GEN_SWIFT" ]] || fail "PROTOC_GEN_SWIFT is not executable"
    printf '%s' "$PROTOC_GEN_SWIFT"; return
  fi
  [[ -d "$SWIFT_PROTOBUF_CHECKOUT" ]] || swift package --package-path "$ROOT_DIR/IMV2Server" resolve >/dev/null
  local build_arguments=(swift build --package-path "$SWIFT_PROTOBUF_CHECKOUT" -c release --product protoc-gen-swift)
  if [[ -n "$SWIFT_PROTOBUF_PLUGIN_SCRATCH_PATH" ]]; then
    mkdir -p "$SWIFT_PROTOBUF_PLUGIN_SCRATCH_PATH"
    build_arguments+=(--scratch-path "$SWIFT_PROTOBUF_PLUGIN_SCRATCH_PATH")
  fi
  "${build_arguments[@]}" >/dev/null
  local plugin
  local build_root="${SWIFT_PROTOBUF_PLUGIN_SCRATCH_PATH:-$SWIFT_PROTOBUF_CHECKOUT/.build}"
  plugin="$(find "$build_root" -path '*/release/protoc-gen-swift' -type f | sort | head -n 1)"
  [[ -x "$plugin" ]] || fail "unable to locate protoc-gen-swift"
  printf '%s' "$plugin"
}

command -v protoc >/dev/null || fail "protoc is required"
[[ -f "$PROTO_FILE" ]] || fail "V2 proto is missing"
VERSION="$(tr -d '[:space:]' < "$PROTO_DIR/protocol_version.txt")"
[[ "$VERSION" =~ ^[0-9]+$ ]] || fail "protocol_version.txt must be an integer"
PLUGIN="$(resolve_plugin)"
mkdir -p "$CLIENT_OUT" "$SERVER_OUT" "$(dirname "$CLIENT_VERSION")" "$(dirname "$SERVER_VERSION")"

for output in "$CLIENT_OUT" "$SERVER_OUT"; do
  protoc --plugin="protoc-gen-swift=$PLUGIN" --proto_path="$ROOT_DIR/Protocol" --swift_opt=Visibility=Public --swift_out="$output" "$PROTO_FILE"
done
for version_file in "$CLIENT_VERSION" "$SERVER_VERSION"; do
  cat > "$version_file" <<SWIFT
// Generated by scripts/generate_v2_protobuf.sh. Do not edit manually.
public enum IMV2ProtocolVersion {
    public static let current: UInt32 = $VERSION
    public static let currentInt: Int = $VERSION
}
SWIFT
done
